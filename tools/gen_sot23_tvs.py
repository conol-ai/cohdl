#!/usr/bin/env python3
"""Generate the SOT-23 two-line TVS arrays of ``lib/esd``.

``python3 -I tools/gen_sot23_tvs.py [--check]`` writes ``lib/esd/src/sot23.cohdl`` and
its evidence record ``lib/esd/docs/sot23.evidence.md`` from
``tools/discrete_data/sot23_tvs.json``, a transcription of the manufacturer
datasheets of the SOT-23 TVS arrays in the B1 snapshot. With ``--check`` it
writes nothing and fails if a committed file differs.

Every part protects two lines on pins 1 and 2 against a common terminal on
pin 3, on ``sot::SOT3P190X290X130N``. Its device is the circuit its own sheet
draws between those pins: two bidirectional TVS, two unidirectional TVS with
a common anode, a steering-diode array, or an asymmetric pair (the RS-485
type, one working voltage with the lines positive and another with them
negative). The tool fails closed on another pin assignment, an unknown
circuit, a repeated MPN or a missing working voltage. Nothing is fetched,
and no supplier binding is written.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from gen_sot23 import LAND, MFR_SHORT, WIDTH, DataError, literal  # noqa: E402

DATA = ROOT / "tools" / "discrete_data" / "sot23_tvs.json"
OUT = ROOT / "lib" / "esd" / "src" / "sot23.cohdl"
EVIDENCE = ROOT / "lib" / "esd" / "docs" / "sot23.evidence.md"
SHORT = dict(MFR_SHORT, ProTek="PROTEK")
PINS = {"1": "IO1", "2": "IO2", "3": "GND"}
DEVICES = {
    "bidirectional": ("TVS2Bi_SOT23", "<VRWM: Voltage>",
                      "two bidirectional TVS, one from each line (pins 1 and 2) to pin 3"),
    "unidirectional": ("TVS2Uni_SOT23", "<VRWM: Voltage>",
                       "two unidirectional TVS, cathodes on the lines (pins 1 and 2), common anode on pin 3"),
    "steering": ("TVS2Steering_SOT23", "<VRWM: Voltage>",
                 "a low-capacitance steering-diode array: each line has a diode to pin 3 and one to an internal "
                 "rail clamped to pin 3"),
    "asymmetric": ("TVS2Asym_SOT23", "<VRWM: Voltage, VRWM_REV: Voltage>",
                   "an asymmetric pair per line (RS-485 type): VRWM with the lines positive to pin 3, VRWM_REV "
                   "with them negative"),
}


def part_name(row: dict) -> str:
    return "ESD_%s_%s" % (SHORT[row["mfr"]], re.sub(r"[^A-Za-z0-9]+", "_", row["mpn"]).strip("_"))


def args(row: dict) -> str:
    r = row["ratings"]
    if row["config"] == "asymmetric":
        return f"{literal(r['vrwm_v'], 'V')}, {literal(r['vrwm_reverse_v'], 'V')}"
    return literal(r["vrwm_v"], "V")


def comment(row: dict) -> str:
    r = row["ratings"]
    text = f"VRWM {r['VRWM']}; VBR {r['VBR']}; VC {r['VC']}; IPP {r['IPP']}"
    if row.get("marking"):
        text += f"; marking {row['marking']}"
    return f"// {row['mpn']} ({row['c']}): {text}"


def check(rows: list[dict]) -> None:
    seen = set()
    for row in rows:
        if row["config"] not in DEVICES:
            raise DataError(f"gen_sot23_tvs.py: {row['mpn']}: unknown circuit {row['config']!r}")
        if row["pins"] != PINS:
            raise DataError(f"gen_sot23_tvs.py: {row['mpn']}: pins {row['pins']} are not {PINS}")
        if (row["mfr"], row["mpn"]) in seen or part_name(row) in {part_name(r) for r in rows if r is not row}:
            raise DataError(f"gen_sot23_tvs.py: {row['mfr']} {row['mpn']} appears twice")
        seen.add((row["mfr"], row["mpn"]))
        if not re.fullmatch(r"[0-9a-f]{64}", row["datasheet"]["sha256"]):
            raise DataError(f"gen_sot23_tvs.py: {row['mpn']}: no datasheet checksum")
        args(row)


def primary(row: dict) -> list[str]:
    head = f'    primary {{ mfr: "{row["mfr"]}", mpn: "{row["mpn"]}",'
    line = f"{head} footprint: {LAND} }}"
    return [line] if len(line) <= WIDTH else [head, f"              footprint: {LAND} }}"]


def source(rows: list[dict]) -> str:
    out = ["// SOT-23 two-line TVS arrays of the B1 snapshot (library plan W4, item 3d).",
           "//",
           "// GENERATED by tools/gen_sot23_tvs.py from tools/discrete_data/sot23_tvs.json",
           "// — do not hand-edit. Each device is the circuit the part's own sheet draws",
           "// between its numbered SOT-23 pins: the two protected lines on pins 1 and 2,",
           "// the common terminal on pin 3. The sheets and their checksums are in",
           "// docs/sot23.evidence.md. Every part sits on sot::SOT3P190X290X130N, the",
           "// audited SOT-23-3 land on the assembler's frame. No part carries a supplier",
           "// binding yet: it is bound only with its own preview reading.",
           ""]
    for config, (name, generics, what) in DEVICES.items():
        if not any(r["config"] == config for r in rows):
            continue
        out += [f"// Two-line TVS array, SOT-23: {what}.", '#[doc("docs/sot23.evidence.md")]',
                f"pub device {name}{generics} {{", "    pins {",
                "        required IO1: 1 [bidirectional]", "        required IO2: 2 [bidirectional]",
                "        required GND: 3 [power_in]", "    }", "}", "", f"impl ESD_Protector for {name} {{}}", ""]
    for config, (name, _, _) in DEVICES.items():
        members = [r for r in rows if r["config"] == config]
        if not members:
            continue
        out += [f"// ---- {name}: {len(members)} parts ----", ""]
        for row in members:
            out += [comment(row), '#[doc("docs/sot23.evidence.md")]',
                    f"pub part {part_name(row)}: {name}<{args(row)}> {{", *primary(row), "}", ""]
    return "\n".join(out)


def evidence(rows: list[dict]) -> str:
    out = ["# SOT-23 two-line TVS arrays: datasheet evidence", "",
           "Generated by `tools/gen_sot23_tvs.py` from `tools/discrete_data/sot23_tvs.json`; do not edit.", "",
           "Each part's sheet was fetched on 2026-11-23 through the LCSC datasheet link its B1 snapshot page "
           "(2026-10-30) gives, and its pins and internal circuit read from the sheet's numbered SOT-23 "
           "diagram. The PDFs are not committed; the SHA-256 below identifies each one.", "",
           "| Part | MPN | Manufacturer | Snapshot C number | Circuit | Read from | PDF SHA-256 | Bytes |",
           "|---|---|---|---|---|---|---|---:|"]
    for row in rows:
        d = row["datasheet"]
        out.append(f"| `{part_name(row)}` | {row['mpn']} | {row['mfr']} | {row['c']} | {row['circuit']} | "
                   f"{d['pinout']} | `{d['sha256']}` | {d['bytes']} |")
    notes = [r for r in rows if r.get("notes")]
    if notes:
        out += ["", "## Notes from the sheets", ""]
        out += [f"- {r['mpn']} ({r['c']}): {r['notes']}" for r in notes]
    out += ["", "## Left out", "",
            "- SM712 (C7420375, Zhuhai Hongjiacheng): its sheet draws the 7 V and 12 V directions opposite to "
            "ProTek's PSM712, and its table headers read either way. It waits for the direction to be settled.",
            "", "## Sources", ""]
    out += [f"- {r['mpn']}: <{r['datasheet']['url']}> (fetched {r['datasheet']['fetched']})" for r in rows]
    return "\n".join(out) + "\n"


def outputs() -> dict[Path, str]:
    rows = json.loads(DATA.read_text(encoding="utf-8"))["parts"]
    check(rows)
    return {OUT: source(rows), EVIDENCE: evidence(rows)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    opts = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if opts.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if stale:
        print("gen_sot23_tvs.py: not what the data builds: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

# Devices
# --------------------------------------------------------------------------


def pin_block(variant):
    return (
        f"    pins[{variant}] {{\n"
        f"        required A: 1 [passive]\n"
        f"        required B: 2 [passive]\n"
        f"    }}\n"
    )


def emit_devices(cap_sizes):
    r_variants = [f"R{s}" for s in R_POWER]
    c_variants = [f"C{s}" for s in cap_sizes]
    out = [
        header(
            "The two chip-passive devices, one variant per case size (RFC-008).",
            GENERATED
            + "\n\n"
            + "A variant is not decoration: it carries the size's own rated power, so\n"
            + "`ChipResistor<10kohm, 1%>[R0402]` states 1/16 W and `[R1206]` states\n"
            + "1/4 W from the same declaration. Traits come from std — this library\n"
            + "adds devices and parts, not a second set of trait definitions.",
        ),
        f"pub device ChipResistor<R: Resistance, T: Tolerance = 1%> {{\n"
        f"    variants {{ {', '.join(r_variants)} }}\n\n"
        + "\n".join(pin_block(v) for v in r_variants)
        + "\n    spec {\n        resistance: R\n        tolerance: T\n    }\n"
        + "".join(
            f"    spec[R{size}] {{\n        power_rating: {power}\n    }}\n"
            for size, power in R_POWER.items()
        )
        + "}\n",
        "impl TwoTerminal for ChipResistor {}\n\nimpl Resistor for ChipResistor {}\n",
        f"pub device MLCC<C: Capacitance, V: Voltage = 16V, T: Tolerance = 10%> {{\n"
        f"    variants {{ {', '.join(c_variants)} }}\n\n"
        + "\n".join(pin_block(v) for v in c_variants)
        + "\n    spec {\n        capacitance: C\n        voltage_rating: V\n        tolerance: T\n    }\n"
        + "}\n",
        "impl TwoTerminal for MLCC {}\n\nimpl Capacitor for MLCC {}\n",
    ]
    return "\n".join(out)



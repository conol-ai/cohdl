def mm(v):
    """A Length literal in canonical form: no trailing zeros, always `mm`."""
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return f"{s or '0'}mm"


def header(title, note=""):
    out = [f"// {title}"]
    if note:
        out += ["//"] + [f"// {line}".rstrip() for line in note.strip().split("\n")]
    return "\n".join(out) + "\n"



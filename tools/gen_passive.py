#!/usr/bin/env python3
"""Generate the `passive` library (lib/passive/) — chip resistors and MLCCs.

The catalog is DATA, not hand-authored source: thousands of parts whose only
per-part variation is (size, value, tolerance, dielectric, voltage) and the
manufacturer part numbers those fields encode. Generating it keeps every part
consistent with the same rules, and keeps a value-grid change a one-line edit
here instead of a thousand-line hand edit there.

Run from the repository root:

    python3 tools/gen_passive.py && cargo run -- fmt lib/passive --check

The output is already in `cohdl fmt` canonical form — the `--check` above is
the gate that keeps it that way (a generator that needed `fmt` to fix it up
would make regeneration produce a diff against the committed bytes).

Land patterns come from KiCad's own footprint library (the same provenance
std's chip lands had), resistor land per RFC-021: resistors and capacitors
share one nominal CHIP-<EIA> land, and the resistor's is the more generous.
"""

import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "lib" / "passive" / "src"

# --------------------------------------------------------------------------
# Land patterns — KiCad Resistor_SMD.pretty/R_<EIA>_<metric>Metric.kicad_mod
# (pad size, pad x offset, courtyard extent), transcribed verbatim.
# --------------------------------------------------------------------------

LANDS = {
    "01005": {"metric": "0402", "pad": (0.4, 0.3), "x": 0.25, "cy": (1.2, 0.6)},
    "0201": {"metric": "0603", "pad": (0.46, 0.4), "x": 0.32, "cy": (1.4, 0.7)},
    "0402": {"metric": "1005", "pad": (0.54, 0.64), "x": 0.51, "cy": (1.86, 0.94)},
    "0603": {"metric": "1608", "pad": (0.8, 0.95), "x": 0.825, "cy": (2.96, 1.46)},
    "0805": {"metric": "2012", "pad": (1.025, 1.4), "x": 0.9125, "cy": (3.36, 1.9)},
    "1206": {"metric": "3216", "pad": (1.125, 1.75), "x": 1.4625, "cy": (4.56, 2.26)},
    "1210": {"metric": "3225", "pad": (1.125, 2.65), "x": 1.4625, "cy": (4.56, 3.16)},
    "2010": {"metric": "5025", "pad": (1.225, 2.65), "x": 2.3125, "cy": (6.36, 3.16)},
    "2512": {"metric": "6332", "pad": (1.225, 3.35), "x": 2.9625, "cy": (7.66, 3.86)},
}

# The reference designator sits above the courtyard, same offset std used.
SILK_GAP = 0.7


def mm(v):
    """A Length literal in canonical form: no trailing zeros, always `mm`."""
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return f"{s or '0'}mm"


def header(title, note=""):
    out = [f"// {title}"]
    if note:
        out += ["//"] + [f"// {line}".rstrip() for line in note.strip().split("\n")]
    return "\n".join(out) + "\n"


GENERATED = (
    "GENERATED by tools/gen_passive.py — do not hand-edit.\n"
    "Regenerate after changing the value grid or a vendor's part-number rule."
)


def emit_pads():
    body = [
        header(
            "Chip-passive pads, one per EIA case size.",
            GENERATED
            + "\n\n"
            + "Geometry: KiCad Resistor_SMD.pretty/R_<EIA>_<metric>Metric.kicad_mod.\n"
            + "Per RFC-021 one CHIP land serves resistors and capacitors alike, and\n"
            + "the resistor land is the more generous of the two.",
        )
    ]
    for eia, land in LANDS.items():
        w, h = land["pad"]
        body.append(
            f"// KiCad R_{eia}_{land['metric']}Metric pad ({mm(w)} x {mm(h)}).\n"
            f"pub pad P_Chip_{eia} {{\n"
            f"    shape: rect\n"
            f"    size: ({mm(w)}, {mm(h)})\n"
            f"    layer: top_copper\n"
            f"    plating: smd\n"
            f"}}\n"
        )
    return "\n".join(body)


def emit_footprints():
    body = [
        header(
            "Chip-passive lands, one per EIA case size (RFC-021 `CHIP_<EIA>`).",
            GENERATED
            + "\n\n"
            + "The footprint's own identifier IS its IPC-7351 name, so a size appears\n"
            + "exactly once in this library: as `CHIP_<EIA>` here, and as the matching\n"
            + "`R<EIA>`/`C<EIA>` device variant.",
        )
    ]
    for eia, land in LANDS.items():
        cw, ch = land["cy"]
        body.append(
            f"pub footprint CHIP_{eia} {{\n"
            f"    pad 1: P_Chip_{eia} at ({mm(-land['x'])}, 0mm)\n"
            f"    pad 2: P_Chip_{eia} at ({mm(land['x'])}, 0mm)\n"
            f"    courtyard {{ shape: rect, at: (0mm, 0mm), size: ({mm(cw)}, {mm(ch)}) }}\n"
            f"    silkscreen_ref {{ at: (0mm, {mm(-(ch / 2 + SILK_GAP))}) }}\n"
            f"}}\n"
        )
    return "\n".join(body)


# --------------------------------------------------------------------------
# Second sources for MLCCs.
#
# Samsung CL and Murata GRM part numbers carry a per-part thickness/electrode
# field that (size, dielectric, voltage, capacitance) does not determine — so
# unlike Yageo's and Vishay's, theirs cannot be derived, and CoHDL requires a
# real `mpn` on every `alt` (E802). Only individually verified numbers appear
# here; a part missing from this table ships with its Yageo primary alone
# rather than with an invented alternate.
# --------------------------------------------------------------------------

def load_verified():
    """MPN -> whether Yageo publishes a specsheet for it.

    Written by tools/verify_passive_mpns.py. Absent file = nothing known yet,
    in which case the datasheet tables alone decide (the pre-verification
    state). A recorded `false` always wins: it means the endpoint that serves
    every real Yageo part has never heard of this one.
    """
    import json

    path = pathlib.Path(__file__).resolve().parent / "passive_data" / "yageo_verified.json"
    if not path.is_file():
        return {}
    return json.loads(path.read_text())["verdicts"]


def load_samsung():
    """(size, volts, dielectric, farads) -> a real Samsung CL part number."""
    import json

    path = pathlib.Path(__file__).resolve().parent / "passive_data" / "samsung_cl.json"
    return json.loads(path.read_text())["parts"]



#!/usr/bin/env python3
"""Generate the `passive` library (lib/passive/) — chip resistors and MLCCs.

The catalog is DATA, not hand-authored source: thousands of parts whose only
per-part variation is (size, value, tolerance, dielectric, voltage) and the
manufacturer part numbers those fields encode. Generating it keeps every part
consistent with the same rules, and keeps a value-grid change a one-line edit
here instead of a thousand-line hand edit there.

Run from the repository root:

    python3 tools/gen_passive.py && cargo run -- fmt lib/passive --check

The output is already in `cohdl fmt` canonical form — the `--check` above is
the gate that keeps it that way (a generator that needed `fmt` to fix it up
would make regeneration produce a diff against the committed bytes).

Land patterns come from KiCad's own footprint library (the same provenance
std's chip lands had), resistor land per RFC-021: resistors and capacitors
share one nominal CHIP-<EIA> land. The geometry is independently checked
against Vishay's official CRCW reflow lands and Samsung's official MLCC reflow
table; see lib/passive/docs/README.md for the comparison and source checksums.
"""

